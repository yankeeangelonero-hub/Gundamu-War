/* v0.4-slice-01 deck-run-model — headless determinism + comparison check.
 * Uses the SAME core as the browser harness (sim.js). Produces evidence for:
 *   AC-2 each run model deterministic (same inputs+seed => byte-identical events)
 *   AC-3 comparison across a fixed matchup set (outcome + legibility/variance/fidelity signals)
 *   AC-5 a non-deterministic model (unseeded shuffle) is DETECTED by the diff (negative control)
 * Run: node experiments/dual-layer/runmode-check.cjs
 * Evidence written under: Project Version/Version 0.4/Slices/Unit Tests/evidence/
 */
const fs = require('fs');
const path = require('path');
const S = require('./sim.js');

const OUT = path.join(__dirname, '..', '..', 'Project Version', 'Version 0.4', 'Slices', 'Unit Tests', 'evidence');
fs.mkdirSync(OUT, { recursive: true });

const MODES = ['construction', 'round', 'draw', 'hybrid'];
const SEED = 0xC0FFEE;

// Comparison set: aligned / misaligned / counter / heavy — vs the fixed rival GHOST.
const MATCHUPS = [
  { id: 'aligned-melee',   body: {frame:'light', weapon:'saber', support:'none'},    deck: S.PRESETS.Berserker, note:'saber body + aggressive deck (should cohere)' },
  { id: 'misaligned-kite', body: {frame:'light', weapon:'saber', support:'none'},    deck: S.PRESETS.Spacer,    note:'saber body + spacing deck (snap is DEAD; should flounder)' },
  { id: 'counter-ranged',  body: {frame:'light', weapon:'rifle', support:'booster'}, deck: S.PRESETS.Spacer,    note:'rifle body + spacing deck (mirror of the rival)' },
  { id: 'heavy-bruiser',   body: {frame:'heavy', weapon:'saber', support:'shield'},  deck: ['rush','slash','feint','hold','overdrive'], note:'heavy saber + shield, hold-the-line deck' },
];

const rivalBody = { frame: S.GHOST.frame, weapon: S.GHOST.weapon, support: S.GHOST.support };
const key = (res) => JSON.stringify(res.events);
const analyse = (res) => {
  const evA = res.events.filter(e => e.who === 'a');
  return {
    winner: res.win === 'a' ? 'YOU' : 'RIVAL',
    turns: res.turns,
    draw: res.draw,
    hesitations: evA.filter(e => e.sys).length,
    whiffs: evA.filter(e => e.whiff).length,
    deadCards: res.A.dead.length,
  };
};
function run(m, mode, opts) {
  const A = S.makeCombatant(m.body, m.deck, 'YOU');
  const B = S.makeCombatant(rivalBody, S.GHOST.deck, 'RIVAL');
  return S.simulate(A, B, SEED, mode, opts);
}

let pass = true;
const lines = [];
const log = (s) => { lines.push(s); console.log(s); };

log('# v0.4-slice-01 — deck-run-model evidence');
log('generated by experiments/dual-layer/runmode-check.cjs (shared core: sim.js)');
log('seed=' + SEED + '  rival=' + S.GHOST.name + '  matchups=' + MATCHUPS.length);
log('');

// ---- AC-2: determinism per mode (run twice, byte-compare) ----
log('## AC-2 — determinism (same inputs+seed => byte-identical events)');
for (const mode of MODES) {
  let allEqual = true;
  for (const m of MATCHUPS) {
    const k1 = key(run(m, mode));
    const k2 = key(run(m, mode));
    const eq = k1 === k2;
    if (!eq) allEqual = false;
    log(`- ${mode.padEnd(12)} ${m.id.padEnd(16)} run1==run2: ${eq ? 'IDENTICAL' : 'DIVERGED'}  (${k1.length} bytes)`);
  }
  if (!allEqual) pass = false;
  log(`  => ${mode}: ${allEqual ? 'PASS (deterministic)' : 'FAIL'}`);
}
// save a sample paired dump for the draw mode (the one with seeded shuffle) for the record
{
  const m = MATCHUPS[0];
  fs.writeFileSync(path.join(OUT, 'draw-aligned-run1.json'), key(run(m, 'draw')));
  fs.writeFileSync(path.join(OUT, 'draw-aligned-run2.json'), key(run(m, 'draw')));
}
log('');

// ---- AC-5: negative control — unseeded shuffle MUST be detected as non-deterministic ----
log('## AC-5 — non-deterministic model is detected (negative control: unseeded shuffle)');
{
  const m = MATCHUPS[2]; // counter-ranged uses draw spacer deck (has cards to shuffle)
  const broken = [];
  for (let i = 0; i < 5; i++) broken.push(key(run(m, 'draw', { brokenShuffle: true })));
  const uniqueBroken = new Set(broken).size;
  const detected = uniqueBroken > 1;
  log(`- broken (Math.random shuffle): ${uniqueBroken}/5 distinct event streams over same seed`);
  log(`  => divergence ${detected ? 'DETECTED by the diff' : 'NOT detected'} (${detected ? 'PASS' : 'FAIL'})`);
  // recovery: the real seeded shuffle is clean
  const fixedEqual = key(run(m, 'draw')) === key(run(m, 'draw'));
  log(`- recovery (seeded shuffle): run1==run2: ${fixedEqual ? 'IDENTICAL (PASS)' : 'DIVERGED (FAIL)'}`);
  if (!detected || !fixedEqual) pass = false;
}
log('');

// ---- AC-3: comparison across the matchup set ----
log('## AC-3 — comparison (matchup × mode → outcome + signals)');
log('| matchup | mode | winner | turns | dead | whiff | hesit |');
log('|---|---|---|---|---|---|---|');
for (const m of MATCHUPS) {
  for (const mode of MODES) {
    const a = analyse(run(m, mode));
    log(`| ${m.id} | ${mode} | ${a.winner} | ${a.turns} | ${a.deadCards} | ${a.whiffs} | ${a.hesitations} |`);
  }
}
log('');
log('matchup notes:');
for (const m of MATCHUPS) log(`- ${m.id}: ${m.note}`);
log('');
log(pass ? 'RESULT: PASS — all three run models are deterministic; divergence is detectable.'
        : 'RESULT: FAIL — see above.');

fs.writeFileSync(path.join(OUT, 'runmode-comparison.md'), lines.join('\n') + '\n');
process.exit(pass ? 0 : 1);
